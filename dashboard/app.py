"""Microbiome Analysis Dashboard.

Interactive Streamlit viewer for results generated by run_pipeline.py
and run_ml.py. Run the pipeline first, then launch with:
    streamlit run dashboard/app.py
"""
import json
from pathlib import Path

import pandas as pd
import streamlit as st

RESULTS = Path("results")
DIV = RESULTS / "diversity"
ML = RESULTS / "ml"

st.set_page_config(page_title="Microbiome Analysis", layout="wide")
st.title("Microbiome Analysis - Reproducible by Design")
st.caption(
    "Real HMP-adjacent data (122 samples x 122 genera). "
    "Run `python scripts/run_pipeline.py --source gmrepo` first."
)

tab_overview, tab_div, tab_ml = st.tabs(
    ["Overview", "Diversity", "Machine Learning"]
)

with tab_overview:
    st.header("Pipeline summary")
    if (DIV / "summary.json").exists():
        s = json.loads((DIV / "summary.json").read_text())
        col1, col2, col3 = st.columns(3)
        col1.metric("Samples", s["n_samples"])
        col2.metric("Genera", s["n_genera"])
        col3.metric("Mean richness", "{:.1f}".format(s["alpha_means"]["richness"]))
        st.json(s)
    else:
        st.warning("Run the pipeline first to populate results/.")

with tab_div:
    st.header("Diversity analysis")
    if (DIV / "alpha.tsv").exists():
        alpha = pd.read_csv(DIV / "alpha.tsv", sep="\t", index_col=0)
        st.subheader("Alpha diversity (per sample)")
        st.dataframe(alpha.describe().round(3))
        if (DIV / "alpha_histograms.png").exists():
            st.image(str(DIV / "alpha_histograms.png"))
    if (DIV / "pcoa_braycurtis.png").exists():
        st.subheader("PCoA - Bray-Curtis")
        st.image(str(DIV / "pcoa_braycurtis.png"))
    if (DIV / "pcoa_jaccard.png").exists():
        st.subheader("PCoA - Jaccard")
        st.image(str(DIV / "pcoa_jaccard.png"))

with tab_ml:
    st.header("Leakage-safe classification")
    if (ML / "metrics.json").exists():
        m = json.loads((ML / "metrics.json").read_text())
        col1, col2, col3 = st.columns(3)
        col1.metric(
            "Balanced accuracy",
            "{:.3f}".format(m["metrics"]["balanced_accuracy_mean"]),
            delta="+/- {:.3f}".format(m["metrics"]["balanced_accuracy_std"]),
        )
        col2.metric(
            "AUC",
            "{:.3f}".format(m["metrics"].get("auc_mean", 0.0)),
            delta="+/- {:.3f}".format(m["metrics"].get("auc_std", 0.0)),
        )
        col3.metric("Features selected", m["metrics"]["k_features"])
        st.subheader("Top features")
        if (ML / "feature_importance.tsv").exists():
            fi = pd.read_csv(ML / "feature_importance.tsv", sep="\t")
            st.dataframe(fi.head(20))
            st.bar_chart(fi.set_index("taxon")["importance"].head(15))
    else:
        st.warning("Run `python scripts/run_ml.py` first.")
